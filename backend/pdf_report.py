    chart_w = content_w - 92 * mm
    prob_barchart = ProbabilityBarChart(report.probabilities, width=chart_w, height=34 * mm)
    distribution_table = Table([[prob_subtable, prob_barchart]], colWidths=[92 * mm, chart_w])
