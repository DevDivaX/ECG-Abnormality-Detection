    _validate_report_data(report)
    output = io.BytesIO()

    # Document Geometry: A4 (210mm x 297mm), Margins 16mm
    margin = 16 * mm
    doc = SimpleDocTemplate(
        output,
        pagesize=A4,
        rightMargin=margin,
        leftMargin=margin,
        topMargin=14 * mm,
        bottomMargin=14 * mm,
        title="CardioTrace ECG Analysis Report",
        author="CardioTrace",
    )

