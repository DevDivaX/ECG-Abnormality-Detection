import React, { useState } from 'react';
import { AlertCircle, X, ShieldAlert } from 'lucide-react';

export default function DisclaimerBanner() {
  const [dismissed, setDismissed] = useState(false);

  if (dismissed) return null;

  return (
    <div className="bg-amber-500/10 border-b border-amber-500/20 text-amber-200/90 px-4 py-2 text-xs flex items-center justify-between gap-3 no-print">
      <div className="max-w-7xl mx-auto flex items-center gap-2.5">
        <ShieldAlert className="w-4 h-4 text-amber-400 shrink-0" />
        <p className="leading-snug">
          <strong className="font-semibold text-amber-300 mr-1.5">Educational Medical Technology:</strong>
          This application is an educational ECG heartbeat classification project. Its predictions are generated by an experimental machine learning model and are not a medical diagnosis. It is not clinically validated and must not be used to make medical decisions.
        </p>
      </div>
      <button
        onClick={() => setDismissed(true)}
        className="text-amber-400 hover:text-amber-200 p-1 rounded hover:bg-amber-500/20 transition shrink-0"
        title="Dismiss disclaimer"
        aria-label="Dismiss disclaimer"
      >
        <X className="w-3.5 h-3.5" />
      </button>
    </div>
  );
}
